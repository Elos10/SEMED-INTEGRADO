-- Fonte corporativa única de pessoas vinculada ao Supabase Auth.
create table if not exists public.semed_people (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists semed_people_email_lower_idx on public.semed_people (lower(email));

insert into public.semed_people (user_id,email,full_name,active)
select id, lower(email), coalesce(raw_user_meta_data->>'full_name', raw_user_meta_data->>'name', split_part(email,'@',1)), true
from auth.users where email is not null
on conflict (user_id) do update set email=excluded.email, updated_at=now();

create or replace function private.sync_semed_person_from_auth()
returns trigger language plpgsql security definer set search_path=public,auth,pg_temp as $$
begin
  insert into public.semed_people(user_id,email,full_name,active,updated_at)
  values(new.id,lower(coalesce(new.email,'')),coalesce(new.raw_user_meta_data->>'full_name',new.raw_user_meta_data->>'name',split_part(coalesce(new.email,''),'@',1)),true,now())
  on conflict(user_id) do update set email=excluded.email,
    full_name=case when public.semed_people.full_name='' then excluded.full_name else public.semed_people.full_name end,
    updated_at=now();
  return new;
end $$;
revoke all on function private.sync_semed_person_from_auth() from public, anon, authenticated;
drop trigger if exists semed_auth_user_sync on auth.users;
create trigger semed_auth_user_sync after insert or update of email,raw_user_meta_data on auth.users
for each row execute function private.sync_semed_person_from_auth();

alter table public.semed_people enable row level security;
drop policy if exists semed_people_read_self on public.semed_people;
create policy semed_people_read_self on public.semed_people for select to authenticated
using (user_id=(select auth.uid()));
revoke all on public.semed_people from anon;
grant select on public.semed_people to authenticated;

create table if not exists public.semed_audit (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  module_code text not null,
  action text not null,
  entity_type text,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists semed_audit_user_created_idx on public.semed_audit(user_id,created_at desc);
create index if not exists semed_audit_module_created_idx on public.semed_audit(module_code,created_at desc);
alter table public.semed_audit enable row level security;
drop policy if exists semed_audit_insert_own on public.semed_audit;
create policy semed_audit_insert_own on public.semed_audit for insert to authenticated
with check (user_id=(select auth.uid()) and private.semed_can_module(module_code,'view'));
drop policy if exists semed_audit_read_own on public.semed_audit;
create policy semed_audit_read_own on public.semed_audit for select to authenticated
using (user_id=(select auth.uid()));
revoke all on public.semed_audit from anon;
grant select,insert on public.semed_audit to authenticated;
grant usage,select on sequence public.semed_audit_id_seq to authenticated;

create or replace function public.get_my_modules()
returns table(codigo text,nome text,descricao text,icone text,rota text,ordem integer)
language sql stable security definer set search_path=public,pg_temp as $$
  select distinct m.code,m.name,m.description,m.icon,m.route,m.display_order
  from public.semed_people person
  join public.semed_user_profiles up on up.user_id=person.user_id and up.active
  join public.semed_profiles p on p.id=up.profile_id and p.active
  join public.semed_profile_module_permissions permission on permission.profile_id=p.id and permission.can_view
  join public.semed_modules m on m.id=permission.module_id and m.active
  where person.user_id=auth.uid() and person.active
  order by m.display_order,m.name
$$;
revoke all on function public.get_my_modules() from public,anon;
grant execute on function public.get_my_modules() to authenticated;

create or replace function public.get_my_access_context()
returns jsonb language sql stable security definer set search_path=public,pg_temp as $$
  select case when auth.uid() is null then null else jsonb_build_object(
    'user', jsonb_build_object('id',person.user_id,'email',person.email,'full_name',person.full_name,'active',person.active),
    'profiles', coalesce((select jsonb_agg(distinct jsonb_build_object('code',p.code,'name',p.name))
      from public.semed_user_profiles up join public.semed_profiles p on p.id=up.profile_id
      where up.user_id=person.user_id and up.active and p.active),'[]'::jsonb),
    'modules', coalesce((select jsonb_agg(jsonb_build_object('code',module_access.code,'name',module_access.name,'route',module_access.route,
      'permissions',jsonb_build_object('view',module_access.can_view,'create',module_access.can_create,'edit',module_access.can_edit,
      'delete',module_access.can_delete,'approve',module_access.can_approve,'admin',module_access.can_admin)) order by module_access.display_order)
      from (select m.code,m.name,m.route,m.display_order,bool_or(pm.can_view) can_view,bool_or(pm.can_create) can_create,
        bool_or(pm.can_edit) can_edit,bool_or(pm.can_delete) can_delete,bool_or(pm.can_approve) can_approve,bool_or(pm.can_admin) can_admin
        from public.semed_user_profiles up
        join public.semed_profiles p on p.id=up.profile_id and p.active
        join public.semed_profile_module_permissions pm on pm.profile_id=p.id
        join public.semed_modules m on m.id=pm.module_id and m.active
        where up.user_id=person.user_id and up.active group by m.id,m.code,m.name,m.route,m.display_order) module_access),'[]'::jsonb)
  ) end
  from public.semed_people person where person.user_id=auth.uid() and person.active
$$;
revoke all on function public.get_my_access_context() from public,anon;
grant execute on function public.get_my_access_context() to authenticated;
